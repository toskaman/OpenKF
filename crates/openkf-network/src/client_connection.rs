//! Client Connection Handshake State Machine for Unreal Engine 2.5 / Killing Floor v1065.
//!
//! Handles the connection lifecycle from initial hostname resolution through transport handshake,
//! challenge negotiation, protocol verification (1065), server login, welcome map transfer,
//! and level loading transitions.

use crate::bunch::{FInBunch, FOutBunch};
use crate::channel::{ControlChannel, ControlEvent, NetworkMessageType};
use crate::error::{NetworkError, NetworkResult};
use std::net::{SocketAddr, ToSocketAddrs};

/// Client connection handshake states for Unreal Engine 2.5 / Killing Floor v1065.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ClientConnectionState {
    /// Initial or reset state; no active connection.
    Disconnected,
    /// Resolving hostname or server address.
    Resolving,
    /// Socket bound or address resolved; initiating transport handshake.
    Handshaking,
    /// Sent `NMT_Hello` with protocol version 1065; awaiting server response (Challenge or Upgrade).
    SendingHello,
    /// Received server Challenge, dispatched `NMT_Login`; awaiting server `NMT_Welcome`.
    AwaitingWelcome,
    /// Received `NMT_Welcome` with map name and player ID; handshake completed successfully.
    Connected,
    /// Client has transitioned to loading the welcomed level / map geometry and assets.
    LevelLoading,
}

impl ClientConnectionState {
    /// Returns true if the state represents a disconnected state.
    #[inline]
    pub fn is_disconnected(&self) -> bool {
        matches!(self, Self::Disconnected)
    }

    /// Returns true if currently resolving server address.
    #[inline]
    pub fn is_resolving(&self) -> bool {
        matches!(self, Self::Resolving)
    }

    /// Returns true if in any active handshake phase prior to completion.
    #[inline]
    pub fn is_handshaking(&self) -> bool {
        matches!(
            self,
            Self::Handshaking | Self::SendingHello | Self::AwaitingWelcome
        )
    }

    /// Returns true if the handshake completed and connection is established.
    #[inline]
    pub fn is_connected(&self) -> bool {
        matches!(self, Self::Connected)
    }

    /// Returns true if currently loading the map specified in `NMT_Welcome`.
    #[inline]
    pub fn is_level_loading(&self) -> bool {
        matches!(self, Self::LevelLoading)
    }
}

/// Helper trait allowing `process_packet` to accept both `&FInBunch` and owned `FInBunch`.
pub trait AsBunchRef {
    fn as_bunch_ref(&self) -> &FInBunch;
}

impl AsBunchRef for FInBunch {
    #[inline]
    fn as_bunch_ref(&self) -> &FInBunch {
        self
    }
}

impl AsBunchRef for &FInBunch {
    #[inline]
    fn as_bunch_ref(&self) -> &FInBunch {
        self
    }
}

impl AsBunchRef for &mut FInBunch {
    #[inline]
    fn as_bunch_ref(&self) -> &FInBunch {
        self
    }
}

/// Client connection handshake state machine (`UPendingNetGame` / `UNetConnection`).
///
/// Orchestrates the multi-stage connection sequence over Control Channel 0:
/// 1. Address resolution (`Resolving`)
/// 2. Initial handshake initialization (`Handshaking`)
/// 3. Protocol version announcement (`SendingHello` with v1065)
/// 4. Server challenge verification and login (`AwaitingWelcome`)
/// 5. Successful join and level loading (`Connected` -> `LevelLoading`)
#[derive(Debug)]
pub struct ClientConnectionStateMachine {
    /// Current state of the connection lifecycle.
    state: ClientConnectionState,
    /// Negotiated protocol version (default: 1065 for retail Killing Floor).
    protocol_version: u32,
    /// Target server socket address.
    server_addr: Option<SocketAddr>,
    /// Raw address string passed to `connect_to`.
    server_address_str: Option<String>,
    /// Underlying Control Channel 0 instance.
    pub control_channel: ControlChannel,
    /// 32-bit challenge received from the server.
    challenge: Option<u32>,
    /// Client player name for login.
    player_name: String,
    /// Client options string for login (e.g. `?Class=KFMod.KFPlayerPawn`).
    player_options: String,
    /// Player ID assigned by the server in `NMT_Welcome`.
    player_id: Option<u32>,
    /// Level / map name received in `NMT_Welcome`.
    map_name: Option<String>,
    /// Error message if handshake failed or disconnected.
    failure_reason: Option<String>,
    /// Outgoing bunches generated by state machine transitions waiting to be transmitted.
    pending_out_bunches: Vec<FOutBunch>,
    /// If true, automatically transitions from `Connected` to `LevelLoading` upon receiving `NMT_Welcome`.
    auto_level_loading: bool,
}

impl Default for ClientConnectionStateMachine {
    fn default() -> Self {
        Self::new(1065)
    }
}

impl ClientConnectionStateMachine {
    /// Creates a new connection state machine configured for the given protocol version (e.g. 1065).
    pub fn new(protocol_version: u32) -> Self {
        Self {
            state: ClientConnectionState::Disconnected,
            protocol_version,
            server_addr: None,
            server_address_str: None,
            control_channel: ControlChannel::new(protocol_version),
            challenge: None,
            player_name: "Player".to_string(),
            player_options: "?Class=KFMod.KFPlayerPawn".to_string(),
            player_id: None,
            map_name: None,
            failure_reason: None,
            pending_out_bunches: Vec::new(),
            auto_level_loading: false,
        }
    }

    /// Builder method to set the player display name.
    pub fn with_player_name(mut self, name: impl Into<String>) -> Self {
        self.player_name = name.into();
        self
    }

    /// Builder method to set player login options.
    pub fn with_player_options(mut self, options: impl Into<String>) -> Self {
        self.player_options = options.into();
        self
    }

    /// Builder method to configure automatic level loading transition upon Welcome.
    pub fn with_auto_level_loading(mut self, auto: bool) -> Self {
        self.auto_level_loading = auto;
        self
    }

    /// Initiates a connection to the specified address (e.g. `"127.0.0.1:7707"`, `"kf.server.com:7707"`, or `"127.0.0.1"`).
    ///
    /// Transitions state through:
    /// `Disconnected` -> `Resolving` -> `Handshaking` -> `SendingHello`.
    ///
    /// Generates and queues the initial `NMT_Hello` bunch with protocol version 1065.
    pub fn connect_to(&mut self, addr: &str) -> NetworkResult<()> {
        self.reset();
        self.server_address_str = Some(addr.to_string());
        self.state = ClientConnectionState::Resolving;

        // Resolve address: if port is omitted, default to 7707 (retail Killing Floor port)
        let resolved_addr = if let Ok(sa) = addr.parse::<SocketAddr>() {
            sa
        } else {
            let addr_with_port = if addr.contains(':') {
                addr.to_string()
            } else {
                format!("{addr}:7707")
            };

            match addr_with_port.to_socket_addrs() {
                Ok(mut iter) => iter.next().ok_or_else(|| {
                    let err = format!("No IP addresses found for host: {addr}");
                    self.fail(err.clone());
                    NetworkError::Disconnected(err)
                })?,
                Err(e) => {
                    let err = format!("Address resolution error for {addr}: {e}");
                    self.fail(err.clone());
                    return Err(NetworkError::Disconnected(err));
                }
            }
        };

        self.server_addr = Some(resolved_addr);
        self.state = ClientConnectionState::Handshaking;

        // Send NMT_Hello with protocol version
        self.state = ClientConnectionState::SendingHello;
        let hello_bunch = self.control_channel.create_hello_bunch();
        self.pending_out_bunches.push(hello_bunch);

        Ok(())
    }

    /// Initiates a connection directly to a known `SocketAddr`.
    pub fn connect_to_addr(&mut self, addr: SocketAddr) -> NetworkResult<()> {
        self.connect_to(&addr.to_string())
    }

    /// Processes an incoming bunch received from the server.
    ///
    /// When receiving control messages on Channel 0:
    /// - `NMT_Challenge`: Parses 32-bit challenge, responds with `NMT_Login`, transitions to `AwaitingWelcome`.
    /// - `NMT_Welcome`: Extracts map name and player ID, transitions to `Connected` (or `LevelLoading`).
    /// - `NMT_Upgrade`: Detects protocol mismatch, transitions to `Disconnected`.
    /// - `NMT_Failure`: Extracts server rejection reason, transitions to `Disconnected`.
    pub fn process_packet<B: AsBunchRef>(&mut self, bunch: B) -> NetworkResult<Option<ControlEvent>> {
        let b = bunch.as_bunch_ref();

        // Control channel messages only arrive on Channel 0
        if b.channel_index != 0 {
            return Ok(None);
        }

        let mut reader = b.payload_reader();
        if reader.remaining_bits() < 8 {
            return Ok(None);
        }

        let msg_byte = reader.read_u8()?;
        let msg_type = NetworkMessageType::from_u8(msg_byte);

        match msg_type {
            Some(NetworkMessageType::Challenge) => {
                let challenge = reader.read_u32().unwrap_or(0);
                self.challenge = Some(challenge);

                // Handshake step: server accepted protocol, challenged client
                self.state = ClientConnectionState::AwaitingWelcome;

                // Send NMT_Login containing player name, options, challenge token, and protocol version
                let options = if self.player_options.is_empty() {
                    format!("?Challenge={}&Protocol={}", challenge, self.protocol_version)
                } else {
                    format!(
                        "{}?Challenge={}&Protocol={}",
                        self.player_options, challenge, self.protocol_version
                    )
                };

                let login_bunch = self.control_channel.create_login_bunch(&self.player_name, &options);
                self.pending_out_bunches.push(login_bunch);

                Ok(Some(ControlEvent::ChallengeReceived { challenge }))
            }
            Some(NetworkMessageType::Welcome) => {
                let map_name = reader.read_string().unwrap_or_default();
                let player_id = reader.read_u32().unwrap_or(0);
                self.map_name = Some(map_name.clone());
                self.player_id = Some(player_id);

                // Server approved login and assigned level
                self.state = ClientConnectionState::Connected;
                if self.auto_level_loading {
                    self.state = ClientConnectionState::LevelLoading;
                }

                Ok(Some(ControlEvent::WelcomeReceived { map_name, player_id }))
            }
            Some(NetworkMessageType::Upgrade) => {
                let required_ver = reader.read_u32().unwrap_or(0);
                let err = format!(
                    "Protocol version mismatch: Server requires protocol {required_ver}, client is {}",
                    self.protocol_version
                );
                self.fail(err);
                Ok(Some(ControlEvent::UnknownMessage {
                    msg_type: msg_byte,
                    text: format!("Upgrade required to {required_ver}"),
                }))
            }
            Some(NetworkMessageType::Failure) => {
                let reason = reader.read_string().unwrap_or_else(|_| "Connection rejected by server".into());
                self.fail(reason.clone());
                Ok(Some(ControlEvent::FailureReceived { reason }))
            }
            Some(NetworkMessageType::Hello) => {
                let ver = reader.read_u32().unwrap_or(0);
                Ok(Some(ControlEvent::HelloReceived { protocol_version: ver }))
            }
            _ => {
                let text = reader.read_string().unwrap_or_default();
                Ok(Some(ControlEvent::UnknownMessage { msg_type: msg_byte, text }))
            }
        }
    }

    /// Alias for `process_packet` accepting a bunch reference.
    #[inline]
    pub fn process_bunch(&mut self, bunch: &FInBunch) -> NetworkResult<Option<ControlEvent>> {
        self.process_packet(bunch)
    }

    /// Processes a raw UDP packet buffer, extracting and handling any bunches destined for Channel 0.
    pub fn process_raw_packet(&mut self, data: &[u8]) -> NetworkResult<Vec<ControlEvent>> {
        let (_header, bunches) = crate::packet::parse_packet(data)?;
        let mut events = Vec::new();
        for bunch in bunches {
            if bunch.channel_index == 0 {
                if let Some(event) = self.process_packet(&bunch)? {
                    events.push(event);
                }
            }
        }
        Ok(events)
    }

    /// Returns the current connection state.
    #[inline]
    pub fn connection_state(&self) -> ClientConnectionState {
        self.state
    }

    /// Explicitly transitions from `Connected` to `LevelLoading`.
    pub fn start_level_loading(&mut self) -> NetworkResult<()> {
        if self.state != ClientConnectionState::Connected {
            return Err(NetworkError::Disconnected(format!(
                "Cannot start level loading: connection state is {:?}",
                self.state
            )));
        }
        self.state = ClientConnectionState::LevelLoading;
        Ok(())
    }

    /// Signals that level geometry and asset loading is complete, transitioning back to `Connected`.
    pub fn finish_level_loading(&mut self) -> NetworkResult<()> {
        if self.state != ClientConnectionState::LevelLoading {
            return Err(NetworkError::Disconnected(format!(
                "Cannot finish level loading: connection state is {:?}",
                self.state
            )));
        }
        self.state = ClientConnectionState::Connected;
        Ok(())
    }

    /// Returns the target protocol version (e.g. 1065).
    #[inline]
    pub fn protocol_version(&self) -> u32 {
        self.protocol_version
    }

    /// Returns the resolved server socket address.
    #[inline]
    pub fn server_addr(&self) -> Option<SocketAddr> {
        self.server_addr
    }

    /// Returns the server challenge token, if received.
    #[inline]
    pub fn challenge(&self) -> Option<u32> {
        self.challenge
    }

    /// Returns the map name received from `NMT_Welcome`.
    #[inline]
    pub fn map_name(&self) -> Option<&str> {
        self.map_name.as_deref()
    }

    /// Returns the player ID assigned in `NMT_Welcome`.
    #[inline]
    pub fn player_id(&self) -> Option<u32> {
        self.player_id
    }

    /// Returns the failure or disconnect error reason, if any.
    #[inline]
    pub fn failure_reason(&self) -> Option<&str> {
        self.failure_reason.as_deref()
    }

    /// Returns the configured player name.
    #[inline]
    pub fn player_name(&self) -> &str {
        &self.player_name
    }

    /// Sets the player display name.
    pub fn set_player_name(&mut self, name: impl Into<String>) {
        self.player_name = name.into();
    }

    /// Returns the configured player login options.
    #[inline]
    pub fn player_options(&self) -> &str {
        &self.player_options
    }

    /// Sets the player login options string.
    pub fn set_player_options(&mut self, options: impl Into<String>) {
        self.player_options = options.into();
    }

    /// Configures whether `NMT_Welcome` immediately transitions to `LevelLoading`.
    pub fn set_auto_level_loading(&mut self, auto: bool) {
        self.auto_level_loading = auto;
    }

    /// Manually overrides the current connection state.
    pub fn set_state(&mut self, state: ClientConnectionState) {
        self.state = state;
    }

    /// Pops the next pending outgoing bunch from the queue.
    pub fn pop_outgoing_bunch(&mut self) -> Option<FOutBunch> {
        if self.pending_out_bunches.is_empty() {
            None
        } else {
            Some(self.pending_out_bunches.remove(0))
        }
    }

    /// Takes all pending outgoing bunches, clearing the internal queue.
    pub fn take_outgoing_bunches(&mut self) -> Vec<FOutBunch> {
        std::mem::take(&mut self.pending_out_bunches)
    }

    /// Returns the number of pending outgoing bunches.
    #[inline]
    pub fn pending_bunches_count(&self) -> usize {
        self.pending_out_bunches.len()
    }

    /// Returns true if there are outgoing bunches queued.
    #[inline]
    pub fn has_pending_bunches(&self) -> bool {
        !self.pending_out_bunches.is_empty()
    }

    /// Resets the connection state machine back to `Disconnected` and clears queues.
    pub fn reset(&mut self) {
        self.state = ClientConnectionState::Disconnected;
        self.server_addr = None;
        self.server_address_str = None;
        self.challenge = None;
        self.player_id = None;
        self.map_name = None;
        self.failure_reason = None;
        self.pending_out_bunches.clear();
        self.control_channel = ControlChannel::new(self.protocol_version);
    }

    /// Disconnects the active session and resets state.
    pub fn disconnect(&mut self) {
        self.reset();
    }

    fn fail(&mut self, reason: String) {
        self.failure_reason = Some(reason);
        self.state = ClientConnectionState::Disconnected;
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::bitstream::BitWriter;
    use crate::bunch::ChannelType;

    /// Helper to synthesize a server-side Challenge bunch.
    fn create_challenge_bunch(challenge: u32) -> FInBunch {
        let mut writer = BitWriter::new();
        writer.write_u8(NetworkMessageType::Challenge as u8);
        writer.write_u32(challenge);

        FInBunch {
            channel_index: 0,
            channel_type: Some(ChannelType::Control),
            ch_sequence: 1,
            b_open: false,
            b_close: false,
            b_reliable: true,
            b_partial: false,
            b_partial_initial: false,
            b_partial_final: false,
            bit_count: writer.num_bits(),
            payload: writer.into_bytes(),
        }
    }

    /// Helper to synthesize a server-side Welcome bunch.
    fn create_welcome_bunch(map_name: &str, player_id: u32) -> FInBunch {
        let mut writer = BitWriter::new();
        writer.write_u8(NetworkMessageType::Welcome as u8);
        writer.write_string(map_name);
        writer.write_u32(player_id);

        FInBunch {
            channel_index: 0,
            channel_type: Some(ChannelType::Control),
            ch_sequence: 2,
            b_open: false,
            b_close: false,
            b_reliable: true,
            b_partial: false,
            b_partial_initial: false,
            b_partial_final: false,
            bit_count: writer.num_bits(),
            payload: writer.into_bytes(),
        }
    }

    /// Helper to synthesize a server-side Failure bunch.
    fn create_failure_bunch(reason: &str) -> FInBunch {
        let mut writer = BitWriter::new();
        writer.write_u8(NetworkMessageType::Failure as u8);
        writer.write_string(reason);

        FInBunch {
            channel_index: 0,
            channel_type: Some(ChannelType::Control),
            ch_sequence: 1,
            b_open: false,
            b_close: false,
            b_reliable: true,
            b_partial: false,
            b_partial_initial: false,
            b_partial_final: false,
            bit_count: writer.num_bits(),
            payload: writer.into_bytes(),
        }
    }

    /// Helper to synthesize a server-side Upgrade bunch.
    fn create_upgrade_bunch(required_version: u32) -> FInBunch {
        let mut writer = BitWriter::new();
        writer.write_u8(NetworkMessageType::Upgrade as u8);
        writer.write_u32(required_version);

        FInBunch {
            channel_index: 0,
            channel_type: Some(ChannelType::Control),
            ch_sequence: 1,
            b_open: false,
            b_close: false,
            b_reliable: true,
            b_partial: false,
            b_partial_initial: false,
            b_partial_final: false,
            bit_count: writer.num_bits(),
            payload: writer.into_bytes(),
        }
    }

    #[test]
    fn test_client_connection_handshake_lifecycle_success() {
        let mut client = ClientConnectionStateMachine::new(1065)
            .with_player_name("KFSharpshooter")
            .with_player_options("?Class=KFMod.KFPlayerPawn?Perk=Sharpshooter");

        assert_eq!(client.connection_state(), ClientConnectionState::Disconnected);
        assert!(client.connection_state().is_disconnected());

        // 1. Connect to address
        client.connect_to("127.0.0.1:7707").unwrap();
        assert_eq!(client.connection_state(), ClientConnectionState::SendingHello);
        assert!(client.connection_state().is_handshaking());
        assert_eq!(client.server_addr(), Some("127.0.0.1:7707".parse().unwrap()));

        // Check NMT_Hello bunch
        assert_eq!(client.pending_bunches_count(), 1);
        let hello_bunch = client.pop_outgoing_bunch().unwrap();
        assert_eq!(hello_bunch.channel_index, 0);

        // 2. Server sends Challenge
        let challenge_token = 0x1337CAFE;
        let challenge_bunch = create_challenge_bunch(challenge_token);
        let event = client.process_packet(&challenge_bunch).unwrap();
        assert_eq!(
            event,
            Some(ControlEvent::ChallengeReceived {
                challenge: challenge_token
            })
        );
        assert_eq!(client.challenge(), Some(challenge_token));
        assert_eq!(client.connection_state(), ClientConnectionState::AwaitingWelcome);

        // Client responded with NMT_Login
        assert_eq!(client.pending_bunches_count(), 1);
        let login_bunch = client.pop_outgoing_bunch().unwrap();
        assert_eq!(login_bunch.channel_index, 0);

        // 3. Server sends Welcome
        let map_name = "KF-BioticsLab.rom";
        let player_id = 7;
        let welcome_bunch = create_welcome_bunch(map_name, player_id);
        let event = client.process_packet(welcome_bunch).unwrap();
        assert_eq!(
            event,
            Some(ControlEvent::WelcomeReceived {
                map_name: map_name.to_string(),
                player_id,
            })
        );

        assert_eq!(client.connection_state(), ClientConnectionState::Connected);
        assert!(client.connection_state().is_connected());
        assert_eq!(client.map_name(), Some(map_name));
        assert_eq!(client.player_id(), Some(player_id));

        // 4. Client starts Level Loading
        client.start_level_loading().unwrap();
        assert_eq!(client.connection_state(), ClientConnectionState::LevelLoading);
        assert!(client.connection_state().is_level_loading());

        // 5. Client finishes Level Loading
        client.finish_level_loading().unwrap();
        assert_eq!(client.connection_state(), ClientConnectionState::Connected);
    }

    #[test]
    fn test_client_connection_auto_level_loading() {
        let mut client = ClientConnectionStateMachine::new(1065)
            .with_auto_level_loading(true);

        client.connect_to("127.0.0.1:7707").unwrap();
        let _ = client.pop_outgoing_bunch();

        // Send challenge
        let challenge_bunch = create_challenge_bunch(0x55AA55AA);
        client.process_packet(&challenge_bunch).unwrap();
        let _ = client.pop_outgoing_bunch();

        // Send welcome
        let welcome_bunch = create_welcome_bunch("KF-Farm.rom", 1);
        client.process_packet(&welcome_bunch).unwrap();

        // With auto_level_loading enabled, state immediately becomes LevelLoading
        assert_eq!(client.connection_state(), ClientConnectionState::LevelLoading);
        assert_eq!(client.map_name(), Some("KF-Farm.rom"));
    }

    #[test]
    fn test_client_connection_server_failure() {
        let mut client = ClientConnectionStateMachine::new(1065);
        client.connect_to("127.0.0.1:7707").unwrap();

        let failure_bunch = create_failure_bunch("Server is full (6/6 players)");
        let event = client.process_packet(&failure_bunch).unwrap();

        assert_eq!(
            event,
            Some(ControlEvent::FailureReceived {
                reason: "Server is full (6/6 players)".to_string()
            })
        );
        assert_eq!(client.connection_state(), ClientConnectionState::Disconnected);
        assert_eq!(
            client.failure_reason(),
            Some("Server is full (6/6 players)")
        );
    }

    #[test]
    fn test_client_connection_protocol_upgrade_mismatch() {
        let mut client = ClientConnectionStateMachine::new(1065);
        client.connect_to("127.0.0.1:7707").unwrap();

        let upgrade_bunch = create_upgrade_bunch(1066);
        let event = client.process_packet(&upgrade_bunch).unwrap();

        assert!(matches!(event, Some(ControlEvent::UnknownMessage { msg_type: 1, .. })));
        assert_eq!(client.connection_state(), ClientConnectionState::Disconnected);
        assert!(client.failure_reason().unwrap().contains("1066"));
    }

    #[test]
    fn test_client_connection_address_resolution_default_port() {
        let mut client = ClientConnectionStateMachine::new(1065);
        // Connect without explicit port -> should default to 7707
        client.connect_to("127.0.0.1").unwrap();
        assert_eq!(client.server_addr(), Some("127.0.0.1:7707".parse().unwrap()));
    }

    #[test]
    fn test_client_connection_reset_and_disconnect() {
        let mut client = ClientConnectionStateMachine::new(1065);
        client.connect_to("127.0.0.1:7707").unwrap();
        assert_eq!(client.connection_state(), ClientConnectionState::SendingHello);

        client.disconnect();
        assert_eq!(client.connection_state(), ClientConnectionState::Disconnected);
        assert!(client.server_addr().is_none());
        assert!(!client.has_pending_bunches());
    }

    #[test]
    fn test_client_connection_state_predicates() {
        assert!(ClientConnectionState::Disconnected.is_disconnected());
        assert!(ClientConnectionState::Resolving.is_resolving());
        assert!(ClientConnectionState::Handshaking.is_handshaking());
        assert!(ClientConnectionState::SendingHello.is_handshaking());
        assert!(ClientConnectionState::AwaitingWelcome.is_handshaking());
        assert!(ClientConnectionState::Connected.is_connected());
        assert!(ClientConnectionState::LevelLoading.is_level_loading());
    }
}
